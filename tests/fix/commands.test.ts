import { describe, expect, it } from 'vitest';
import { refreshRuns, unlockYarnEntries } from '../../src/fix/commands.js';
import type { FixStep } from '../../src/fix/plan.js';

type Refresh = Extract<FixStep, { kind: 'refresh' }>;

const refresh = (pkg: string, direct: boolean, extra: Partial<Refresh> = {}): Refresh => ({
  kind: 'refresh',
  package: pkg,
  from: '1.0.0',
  to: '1.0.1',
  direct,
  ...extra,
});

const command = (...argv: string[]) => ({ kind: 'command', argv });

describe('refreshRuns', () => {
  const steps = [
    refresh('zod', true),
    refresh('@xmldom/xmldom', false),
    refresh('string-width', false, { alias: 'string-width-cjs' }),
    refresh('lodash', true, { round: 1 }),
    refresh('a', false),
  ];

  it('gives npm every name in one run, by alias where there is one', () => {
    expect(refreshRuns(steps, 'npm', false)).toEqual([
      command('npm', 'update', '@xmldom/xmldom', 'a', 'lodash', 'string-width-cjs', 'zod', '--package-lock-only'),
    ]);
  });

  it('gives pnpm one round after another, listed names first within a round', () => {
    expect(refreshRuns(steps, 'pnpm', false)).toEqual([
      command('pnpm', 'update', 'zod', '--lockfile-only'),
      command('pnpm', 'update', '@xmldom/xmldom', 'a', 'string-width-cjs', '--lockfile-only'),
      command('pnpm', 'update', 'lodash', '--lockfile-only'),
    ]);
  });

  it('adds -r to every pnpm run in a workspace', () => {
    expect(refreshRuns([refresh('lodash', false)], 'pnpm', true)).toEqual([command('pnpm', 'update', '-r', 'lodash', '--lockfile-only')]);
  });

  it('gives yarn 2+ one `yarn up -R`, and yarn 1 an unlock followed by an install', () => {
    expect(refreshRuns(steps, 'yarn-berry', true)).toEqual([command('yarn', 'up', '-R', '@xmldom/xmldom', 'a', 'lodash', 'string-width-cjs', 'zod')]);
    expect(refreshRuns(steps, 'yarn-classic', false)).toEqual([
      { kind: 'unlock', packages: ['@xmldom/xmldom', 'a', 'lodash', 'string-width-cjs', 'zod'] },
      command('yarn', 'install'),
    ]);
  });

  it('has nothing to run without steps', () => {
    expect(refreshRuns([], 'npm', false)).toEqual([]);
    expect(refreshRuns([], 'yarn-classic', true)).toEqual([]);
  });
});

describe('unlockYarnEntries', () => {
  const lock = [
    '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
    '# yarn lockfile v1',
    '',
    '',
    '"@babel/core@^7.0.0", "@babel/core@^7.1.0":',
    '  version "7.1.0"',
    '',
    'lodash@4.17.20, lodash@^4.17.0:',
    '  version "4.17.20"',
    '',
    '"old-lodash@npm:lodash@3.10.1":',
    '  version "3.10.1"',
    '',
    'ms@2.0.0:',
    '  version "2.0.0"',
    '',
  ].join('\n');

  it('drops every entry of the named packages, by the name each entry is asked for', () => {
    expect(unlockYarnEntries(lock, ['lodash', '@babel/core'])).toBe(
      [
        '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.',
        '# yarn lockfile v1',
        '',
        '',
        '"old-lodash@npm:lodash@3.10.1":',
        '  version "3.10.1"',
        '',
        'ms@2.0.0:',
        '  version "2.0.0"',
        '',
      ].join('\n'),
    );
  });

  it('keeps CRLF line endings', () => {
    const crlf = lock.replaceAll('\n', '\r\n');
    expect(unlockYarnEntries(crlf, ['lodash', '@babel/core'])).toBe(unlockYarnEntries(lock, ['lodash', '@babel/core']).replaceAll('\n', '\r\n'));
  });

  it('keeps the trailing newline when the last entry goes', () => {
    expect(unlockYarnEntries(lock, ['ms']).endsWith('  version "3.10.1"\n')).toBe(true);
  });
});
